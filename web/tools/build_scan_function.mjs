// Writes supabase/functions/fm-lure-scan/index.ts — one self-contained file John pastes into the Supabase dashboard.
// The lure types come from src/lib/data/lures.data.json so the scan's answers always match the app's categories.
// Re-run after adding a lure type:  node tools/build_scan_function.mjs
import fs from "node:fs";
const d = JSON.parse(fs.readFileSync(new URL("../src/lib/data/lures.data.json", import.meta.url)));
const types = Object.entries(d.LURE_PROFILES).map(([k, v]) => [k, v.name]);
const src = `// GENERATED by web/tools/build_scan_function.mjs — edit that file, not this one.
// Supabase Edge Function "fm-lure-scan" (Fishin Magician tackle box): reads a lure (or its package) from a photo with
// Claude's vision. The only place the Anthropic key lives (secret ANTHROPIC_API_KEY; optional ANTHROPIC_MODEL).
// Runs as the signed-in angler, and only answers approved anglers (fm_is_approved()).
//   POST {image_b64, media_type}  →  {visible, brand, product_name, color, size, lure_type, search_query, notes}
import { createClient } from "npm:@supabase/supabase-js@2";

const LURE_TYPES = ${JSON.stringify(types)};
const CORS = { "Access-Control-Allow-Origin": "*", "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type", "Access-Control-Allow-Methods": "POST, OPTIONS" };
const reply = (status, body) => new Response(JSON.stringify(body), { status, headers: { ...CORS, "Content-Type": "application/json" } });
const env = (k) => Deno.env.get(k);
const model = () => (env("ANTHROPIC_MODEL") || "claude-sonnet-5-5").trim();
const publicKey = () => { const k = env("SUPABASE_ANON_KEY"); if (k) return k; try { return Object.values(JSON.parse(env("SUPABASE_PUBLISHABLE_KEYS") || "{}"))[0]; } catch { return undefined; } };
class Friendly extends Error { constructor(msg, status = 502) { super(msg); this.status = status; } }

const TOOL = {
  name: "identify_lure",
  description: "Report what fishing lure is in the photo, from the lure itself and any text on its package.",
  input_schema: { type: "object", additionalProperties: false,
    required: ["visible", "brand", "product_name", "color", "size", "lure_type", "search_query", "notes"],
    properties: {
      visible: { type: "boolean", description: "True if the photo clearly shows a fishing lure or its package." },
      brand: { type: "string", description: "Brand, e.g. 'Strike King'. Empty if you can't tell." },
      product_name: { type: "string", description: "Model/product name as printed (no brand), e.g. 'KVD Squarebill 1.5'. Empty if unknown." },
      color: { type: "string", description: "Color/pattern name as printed, else a short everyday description (e.g. 'green pumpkin')." },
      size: { type: "string", description: "Size or weight if visible (e.g. '1/2 oz', '5 in'), else empty." },
      lure_type: { type: "string", enum: [...LURE_TYPES.map((t) => t[0]), ""], description: "Best-fitting type key from the list in the prompt; empty if none fits." },
      search_query: { type: "string", description: "Short retailer search query: brand + product line (+ color if part of the name)." },
      notes: { type: "string", description: "Anything uncertain, in one short sentence; empty if confident." },
    } },
};
const PROMPT = "This is a phone photo of a bass-fishing lure, or its package, from an angler's tackle box. " +
  "Identify it. Read brand, model, color and size from the package when visible; otherwise judge from the lure itself. " +
  "Pick lure_type from these keys (key = name): " + LURE_TYPES.map(([k, n]) => k + " = " + n).join("; ") + ". " +
  "Notes: a soft plastic sold for several rigs goes under the rig it's most often used on (e.g. Z-Man TRD = ned_rig, Roboworm straight worm = drop_shot, Zoom Fluke = weightless_soft_plastic). " +
  "Answer only by calling the identify_lure tool.";

async function claude(req) {
  const key = (env("ANTHROPIC_API_KEY") || "").trim().replace(/^["']+|["']+$/g, "").trim();
  if (!key) throw new Friendly("The AI key isn't set — add ANTHROPIC_API_KEY under Supabase → Edge Functions → Secrets.", 500);
  for (let attempt = 0; ; attempt++) {
    const r = await fetch("https://api.anthropic.com/v1/messages", { method: "POST",
      headers: { "x-api-key": key, "anthropic-version": "2023-06-01", "content-type": "application/json" }, body: JSON.stringify(req) });
    if (r.ok) return await r.json();
    const text = await r.text(), low = text.toLowerCase();
    if ((r.status === 429 || r.status === 529 || r.status >= 500) && attempt < 3) { await new Promise((res) => setTimeout(res, 1500 * (attempt + 1))); continue; }
    if (r.status === 401) throw new Friendly("The Anthropic API key wasn't accepted — replace ANTHROPIC_API_KEY in Supabase → Edge Functions → Secrets.");
    if (low.includes("credit balance") || low.includes("billing")) throw new Friendly("The Anthropic account is out of credit — add credit at platform.claude.com/settings/billing.");
    if (r.status === 404 || (low.includes("model") && low.includes("not found"))) throw new Friendly("The AI model name isn't recognized (" + model() + ") — set ANTHROPIC_MODEL in Supabase secrets.");
    throw new Friendly("AI error " + r.status + ": " + text.slice(0, 200));
  }
}

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response("ok", { headers: CORS });
  try {
    if (req.method !== "POST") throw new Friendly("Use POST.", 405);
    const sb = createClient(env("SUPABASE_URL"), publicKey(), { global: { headers: { Authorization: req.headers.get("Authorization") || "" } }, auth: { persistSession: false } });
    const ap = await sb.rpc("fm_is_approved");
    if (ap.error || ap.data !== true) throw new Friendly("You're not on the Fishin Magician list.", 403);
    const body = await req.json().catch(() => ({}));
    const b64 = String(body.image_b64 || ""), type = /^image\\/(jpeg|png|webp|gif)$/.test(body.media_type) ? body.media_type : "image/jpeg";
    if (b64.length < 100) throw new Friendly("No photo was sent.", 400);
    if (b64.length > 6_000_000) throw new Friendly("That photo is too large — try again (the app shrinks photos before sending).", 400);
    for (let i = 0; i < 2; i++) {
      const msg = await claude({ model: model(), max_tokens: 1024, tools: [TOOL], tool_choice: { type: "tool", name: "identify_lure" },
        messages: [{ role: "user", content: [{ type: "image", source: { type: "base64", media_type: type, data: b64 } }, { type: "text", text: PROMPT }] }] });
      const use = (msg.content || []).find((b) => b.type === "tool_use" && b.name === "identify_lure");
      if (use) return reply(200, use.input);
    }
    throw new Friendly("The AI answered without filling in the details — please try again.");
  } catch (e) {
    return reply(e instanceof Friendly ? e.status : 500, { error: e instanceof Friendly ? e.message : "Something went wrong: " + String(e).slice(0, 200) });
  }
});
`;
fs.writeFileSync(new URL("../supabase/functions/fm-lure-scan/index.ts", import.meta.url), src);
console.log("wrote supabase/functions/fm-lure-scan/index.ts with", types.length, "lure types");
