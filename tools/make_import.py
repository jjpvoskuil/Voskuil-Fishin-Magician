def read(name, binary=False):
    # ALWAYS the live data branch: main still has stale copies of data/ from before the data branch existed (11-11:
    # reading those gave 73 trips instead of 377)
    out = subprocess.check_output(["git", "-C", str(ROOT), "show", f"origin/data:data/{name}"], stderr=subprocess.DEVNULL)
    return out if binary else out.decode()


def rows(name):
    try:
        return list(csv.DictReader(io.StringIO(read(name))))
    except subprocess.CalledProcessError:
        return []


TAG = "j" + secrets.token_hex(4)


def js(obj):
    s = json.dumps(obj, ensure_ascii=False)
    assert f"${TAG}$" not in s
    return f"${TAG}${s}${TAG}$::jsonb"


def lit(s):
    return "null" if s is None or s == "" else "'" + str(s).replace("'", "''") + "'"


def upsert(table, cols, values, conflict, update):
    if not values:
        return ""
    head = f"insert into public.{table} ({', '.join(cols)}) values\n"
    tail = f"\non conflict ({conflict}) " + ("do nothing" if not update else "do update set " + ", ".join(f"{c} = excluded.{c}" for c in update)) + ";\n"
    out = []
    for i in range(0, len(values), 200):   # keep statements a manageable size
        out.append(head + ",\n".join(values[i:i + 200]) + tail)
    return "".join(out)


PAGE_RENAMES = {"Today (Home)": "Today", "7 Day Forecast": "Forecast", "Spot Session": "Session", "Lake Map": "Map",
                "Development": "Punch list"}


def punch_sql():
    vals, top = [], 0
    for r in rows("dev_tasks.csv"):
        n = int(r["task_no"]); top = max(top, n)
        d = {"description": r.get("description") or "", "page": PAGE_RENAMES.get(r.get("page"), r.get("page") or "General / whole app"),
             "status": r.get("status") or "Open", "priority": "Medium", "author": "John", "created_at": r.get("created_at") or None,
             "updated_at": r.get("completed_at") or r.get("created_at") or None, "completed_at": r.get("completed_at") or None,
             "from_old_app": True}
        vals.append(f"({n}, {lit(DEFAULT_OWNER)}, {js(d)})")
    try:
        nxt = int(read("dev_tasks_counter.txt").strip())
    except (subprocess.CalledProcessError, ValueError):
        nxt = top + 1
    nxt = max(nxt, top + 1)
    sql = upsert("fm_punch", ["task_no", "owner", "data"], vals, "task_no", ["owner", "data"])
    sql += (f"insert into public.fm_punch_counter (id, next_no) values (true, {nxt}) on conflict (id) do update "
            f"set next_no = greatest(public.fm_punch_counter.next_no, excluded.next_no);\n")
    return {"sql": sql, "n": len(vals), "next": nxt}


def main(outdir):
    out = Path(outdir); out.mkdir(parents=True, exist_ok=True)
    sql = ["-- Fishin Magician: data from the old app. Generated by tools/make_import.py - private, don't share.",
           "-- Safe to run more than once (updates rows in place).", "begin;"]
    counts = {}

    # trips
    vals, unknown = [], set()
    for r in rows("trip_log.csv"):
        cond = json.loads(r.pop("conditions_json") or "{}")
        angler = (cond.get("angler") or "").strip()
        owner = EMAILS.get(angler.lower())
        if not owner:
            unknown.add(angler or "(none)"); owner = DEFAULT_OWNER
        data = {**r, "conditions": cond}
        vals.append(f"({lit(r['trip_id'])}, {lit(owner)}, {lit(r['trip_date'])}, {lit(r.get('session_id'))}, {js(data)})")
    sql.append(upsert("fm_trips", ["id", "owner", "trip_date", "session_id", "data"], vals, "id", ["owner", "trip_date", "session_id", "data"]))
    counts["trips"] = len(vals)

    # spots
    vals = []
    for r in rows("lake_spots.csv"):
        d = dict(r)
        for k in ("lat", "lon"):
            d[k] = float(d[k])
        for k in ("main_depth_ft", "transition_depth_ft"):
            d[k] = float(d[k]) if d.get(k) not in (None, "") else None
        vals.append(f"({lit(r['spot_id'])}, {js(d)})")
    sql.append(upsert("fm_spots", ["id", "data"], vals, "id", ["data"]))
    counts["spots"] = len(vals)

    # tackle box (+ own photos)
    vals, photos = [], 0
    photo_dir = out / "lure_photos" / "lures"
    for r in rows("lure_inventory.csv"):
        d = dict(r)
        fn = (r.get("image_filename") or "").strip()
        if fn:
            try:
                raw = read(f"lure_images/{fn}", binary=True)
                stem = f"lures/{r['item_id']}-import"
                if shrink(raw, photo_dir / f"{r['item_id']}-import.jpg", photo_dir / f"{r['item_id']}-import_thumb.jpg"):
                    d["image_path"], d["thumb_path"] = f"{stem}.jpg", f"{stem}_thumb.jpg"; photos += 1
            except subprocess.CalledProcessError:
                print(f"  photo missing for {r['item_id']}: {fn}")
        vals.append(f"({lit(r['item_id'])}, {js(d)})")
    sql.append(upsert("fm_lures", ["id", "data"], vals, "id", ["data"]))
    counts["lures"] = len(vals); counts["lure photos"] = photos

    # Army Corps water-quality readings (add-only)
    vals = []
    for r in rows("water_quality_log.csv"):
        d = {k: (float(v) if v not in ("", None) else None) for k, v in r.items() if k != "observed_at"}
        vals.append(f"({lit(r['observed_at'])}, {js(d)})")
    sql.append(upsert("fm_water_quality", ["observed_at", "data"], vals, "observed_at", None))
    counts["water readings"] = len(vals)

    # frozen forecast scores (add-only)
    vals = []
    for r in rows("segment_score_freeze.csv"):
        d = {"score": float(r["score"]) if r["score"] else None,
             "solunar_overlap": r["solunar_overlap"] if r.get("solunar_overlap") else None,
             "notes": json.loads(r["notes_json"] or "[]"), "breakdown": json.loads(r["breakdown_json"] or "{}"),
             "frozen_at": r.get("frozen_at")}
        vals.append(f"({lit(r['the_date'])}, {lit(r['segment_name'])}, {js(d)})")
    sql.append(upsert("fm_score_freeze", ["the_date", "segment_name", "data"], vals, "the_date, segment_name", None))
    counts["frozen scores"] = len(vals)

    # punch list (numbers kept; counter continues past the old dev_tasks_counter.txt)
    punch = punch_sql()
    sql.append(punch["sql"]); counts["punch items"] = punch["n"]

    sql.append("commit;")
    sql.append("-- check: " + ", ".join(f"{v} {k}" for k, v in counts.items()))
    sql.append("select (select count(*) from public.fm_trips) as trips, (select count(*) from public.fm_spots) as spots, "
               "(select count(*) from public.fm_lures) as lures, (select count(*) from public.fm_water_quality) as water_readings;")
    (out / "punch_list_import.sql").write_text("\n".join([
        "-- Fishin Magician punch list from the old app (tools/make_import.py). Safe to run more than once.", "begin;",
        punch["sql"], "commit;", f"-- check: {punch['n']} items, next number #{punch['next']}",
        "select count(*) as items, (select next_no from public.fm_punch_counter) as next_number from public.fm_punch;"]))
    p = out / "fishin_magician_import.sql"
    p.write_text("\n".join(sql))
    print(f"wrote {p} ({p.stat().st_size / 1e6:.2f} MB): {counts}")
    if unknown:
        print(f"  trips with no known angler (owner set to John): {sorted(unknown)}")


def shrink(raw, full_path, thumb_path):
    """Old-app photo → the new app's sizes (1600 px long edge, 400 px thumbnail), JPEG."""
    try:
        from PIL import Image, ImageOps
    except ImportError:
        print("  (pip install pillow to include photos)"); return False
    im = ImageOps.exif_transpose(Image.open(io.BytesIO(raw))).convert("RGB")
    full_path.parent.mkdir(parents=True, exist_ok=True)
    for path, edge, q in ((full_path, 1600, 90), (thumb_path, 400, 82)):
        c = im.copy(); c.thumbnail((edge, edge)); c.save(path, "JPEG", quality=q)
    return True


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "import_out")
